"""Generate the SDK based on the aas-core-meta model and the snippets."""

import argparse
import os
import pathlib
import re
import subprocess
import sys

import dev_scripts.common as dev_scripts_common

# NOTE (aaronzi, 2026-11-08):
# aas-core-codegen does not emit any copyright or license information, so we
# prepend the header to the generated modules ourselves. Otherwise, the headers
# would be lost on every re-generation.
#
# REUSE-IgnoreStart
_LICENSE_HEADER = """\
# SPDX-FileCopyrightText: 2026 aas-core3.2-python AUTHORS
#
# SPDX-License-Identifier: MIT

"""
# REUSE-IgnoreEnd

_LEADING_SPDX_COMMENTS_RE = re.compile(r"\A(?:#\s*(?:SPDX-[A-Za-z-]+:.*)?\n|\n)*")

_GENERATED_MARKER = "# This code has been automatically generated by aas-core-codegen."


def _prepend_license_header(text: str) -> str:
    """Replace any leading SPDX comment block in ``text`` with our license header."""
    return _LICENSE_HEADER + _LEADING_SPDX_COMMENTS_RE.sub("", text, count=1)


def _add_license_headers(module_dir: pathlib.Path) -> None:
    """Prepend the license header to all the modules generated by aas-core-codegen."""
    for path in sorted(module_dir.glob("*.py")):
        text = path.read_text(encoding="utf-8")
        if _GENERATED_MARKER not in text:
            continue

        path.write_text(_prepend_license_header(text), encoding="utf-8")


def main() -> int:
    """Execute the main routine."""
    repo_root = pathlib.Path(os.path.realpath(__file__)).parent.parent.parent

    default_meta_model_path = os.path.relpath(
        str(repo_root / "dev" / "dev_scripts" / "codegen" / "meta_model.py"),
        os.getcwd(),
    )

    default_snippet_dir = os.path.relpath(
        str(repo_root / "dev" / "dev_scripts" / "codegen" / "snippets"), os.getcwd()
    )

    default_output_dir = os.path.relpath(str(repo_root), os.getcwd())

    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.ArgumentDefaultsHelpFormatter
    )
    parser.add_argument(
        "--meta_model", help="Path to the meta-model", default=default_meta_model_path
    )
    parser.add_argument(
        "--snippet_dir",
        help="Path to the directory containing implementation-specific snippets",
        default=default_snippet_dir,
    )
    parser.add_argument(
        "--output_dir",
        help="Path to the directory where the generated files are to be output",
        default=default_output_dir,
    )
    args = parser.parse_args()

    meta_model_path = pathlib.Path(args.meta_model)
    snippet_dir = pathlib.Path(args.snippet_dir)
    output_dir = pathlib.Path(args.output_dir)

    print(
        f"Transpiling {meta_model_path} "
        f"with snippets from {snippet_dir} "
        f"to {default_output_dir} ..."
    )

    subprocess.run(
        [
            "aas-core-codegen",
            "--model_path",
            str(meta_model_path),
            "--snippets_dir",
            str(snippet_dir),
            "--output_dir",
            str(output_dir),
            "--target",
            "python",
        ],
        check=True,
    )

    # NOTE (aaronzi, 2026-11-08):
    # aas-core-codegen generates both the SDK modules and the unit tests.
    _add_license_headers(output_dir / dev_scripts_common.module_dir())
    _add_license_headers(output_dir / "dev" / "tests")

    return 0


if __name__ == "__main__":
    sys.exit(main())
