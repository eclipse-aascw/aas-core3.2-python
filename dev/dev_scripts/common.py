"""Provide the settings shared among the development scripts."""

import os
import pathlib
import re
from typing import Final

from icontract import ensure

REPO_ROOT: Final[pathlib.Path] = pathlib.Path(
    os.path.realpath(__file__)
).parent.parent.parent

QUALIFIED_MODULE_NAME_PATH: Final[pathlib.Path] = (
    REPO_ROOT
    / "dev"
    / "dev_scripts"
    / "codegen"
    / "snippets"
    / "qualified_module_name.txt"
)


def qualified_module_name() -> str:
    """
    Read the qualified name of the generated module, *e.g.*, ``aas_core3_2``.

    We derive everything from the qualified module name in the snippets so that
    we only have to change that snippet when moving to a new version of
    the meta-model.
    """
    result = QUALIFIED_MODULE_NAME_PATH.read_text(encoding="utf-8").strip()
    if len(result) == 0:
        raise RuntimeError(
            f"The qualified module name is empty in: {QUALIFIED_MODULE_NAME_PATH}"
        )

    return result


@ensure(lambda result: not result.is_absolute())
def module_dir() -> pathlib.Path:
    """
    Determine the directory of the generated module relative to the repo root.

    The qualified module name can include parent modules (*e.g.*,
    ``some.parent.aas_core3_2``), so we map it to nested directories.
    """
    return pathlib.Path(*qualified_module_name().split("."))


def record_mode_variable() -> str:
    """
    Determine the environment variable which switches the tests to record mode.

    This needs to follow the naming in the tests generated by aas-core-codegen.
    """
    return qualified_module_name().replace(".", "_").upper() + "_TESTS_RECORD_MODE"


_VERSION_RE = re.compile(r"^aas_core(?P<major>[0-9]+)_(?P<minor>[0-9]+)$")


def version_stem() -> str:
    """
    Determine the version stem of the meta-model, *e.g.*, ``v3_2``.

    The stem is used both in aas-core-meta and in aas-core-testdatagen.
    """
    name = qualified_module_name()
    mtch = _VERSION_RE.match(name.split(".")[-1])
    if mtch is None:
        raise RuntimeError(
            f"Expected the qualified module name to end with "
            f"aas_core{{major}}_{{minor}}, but got {name!r} "
            f"in {QUALIFIED_MODULE_NAME_PATH}"
        )

    return f"v{mtch.group('major')}_{mtch.group('minor')}"
